#!/usr/bin/env python3
"""Exempt AI providers' published egress ranges from the ndlaw.org jails.

claude.ai, ChatGPT, and similar tools call ndlaw.org/mcp from their own
cloud, so one egress address carries many users. A per-IP ban on it cuts
off every one of them for 10 minutes to 6 hours (this happened to
claude.ai on mcp.ndconst.org, 2026-08-03). Capacity is protected instead
by the app's server-wide cap (NDLAW_MAX_INFLIGHT, ndlaw_mcp/concurrency.py).

Writes /etc/fail2ban/jail.d/ndlaw-ai-egress.local setting `ignoreip` on
each ndlaw jail, and reloads fail2ban only when the content changed. A
failed or implausible fetch keeps the previous file (fail closed to the
last good list, never to an empty one).

Sources (2026-10-15):
  Anthropic — https://platform.claude.com/docs/en/api/ip-addresses
              "Outbound IP addresses", stable, "will not change without
              notice"; HTML only, so the range is pinned here.
  OpenAI    — https://openai.com/chatgpt-connectors.json (connectors, Apps
              SDK, developer mode); changes over time, fetched each run.
  Google    — publishes no egress range for Gemini custom apps; Gemini
              traffic stays under the ordinary per-IP jails.

fail2ban 1.0.2 (Ubuntu 24.04) has no `ignoreip = file:` (added in 1.1.1),
hence the generated drop-in. Run weekly by ndlaw-ai-egress.timer.

usage: update-ai-egress.py [--dry-run] [--out PATH]
"""

from __future__ import annotations

import argparse
import ipaddress
import json
import os
import subprocess
import sys
import tempfile
import urllib.request

OUT = "/etc/fail2ban/jail.d/ndlaw-ai-egress.local"
JAILS = [
    "apache-ndlaw-rate",
    "apache-ndlaw-burst",
    "apache-ndlaw-junk",
    "apache-ndlaw-web-rate",
    "apache-ndlaw-web-burst",
]
ANTHROPIC = ["160.79.104.0/21"]
OPENAI_URL = "https://openai.com/chatgpt-connectors.json"
# The file listed 283 prefixes on 2026-10-06; far fewer means a bad fetch.
OPENAI_MIN = 50


def fetch_openai() -> list[str]:
    req = urllib.request.Request(OPENAI_URL, headers={"User-Agent": "ndlaw-f2b-egress/1"})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = json.load(r)
    nets = []
    for p in data["prefixes"]:
        cidr = p.get("ipv4Prefix") or p.get("ipv6Prefix")
        if cidr:
            nets.append(str(ipaddress.ip_network(cidr, strict=False)))
    if len(nets) < OPENAI_MIN:
        raise ValueError(f"only {len(nets)} OpenAI prefixes (< {OPENAI_MIN})")
    return nets


def render(anthropic: list[str], openai: list[str]) -> str:
    nets = sorted(set(anthropic) | set(openai),
                  key=lambda n: (ipaddress.ip_network(n).version, ipaddress.ip_network(n)))
    # `known/ignoreip` keeps whatever the jail already ignores ([DEFAULT]'s
    # localhost etc.) instead of replacing it.
    value = "%(known/ignoreip)s\n" + "\n".join(f"           {n}" for n in nets)
    head = (
        "# GENERATED by update-ai-egress.py — do not edit; rerun the script.\n"
        f"# {len(anthropic)} Anthropic + {len(openai)} OpenAI ranges.\n"
    )
    body = "".join(f"\n[{j}]\nignoreip = {value}\n" for j in JAILS)
    return head + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()

    try:
        openai = fetch_openai()
    except Exception as e:  # keep the last good file
        print(f"ndlaw-ai-egress: OpenAI fetch failed, keeping {a.out}: {e}", file=sys.stderr)
        return 1
    text = render(ANTHROPIC, openai)

    if a.dry_run:
        sys.stdout.write(text)
        return 0
    try:
        with open(a.out) as f:
            if f.read() == text:
                print("ndlaw-ai-egress: unchanged")
                return 0
    except FileNotFoundError:
        pass

    d = os.path.dirname(a.out)
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".ndlaw-ai-egress.")
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, a.out)
    # `reload` re-reads config without dropping current bans; a config
    # error leaves the running jails as they were and exits non-zero.
    subprocess.run(["fail2ban-client", "reload"], check=True)
    print(f"ndlaw-ai-egress: wrote {a.out} ({len(ANTHROPIC)} + {len(openai)} ranges), reloaded")
    return 0


if __name__ == "__main__":
    sys.exit(main())
